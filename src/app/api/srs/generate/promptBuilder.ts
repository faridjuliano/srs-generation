export function generatePrompt(projectName: string, srsStandard: string, projectVision: string): string;
export function generatePrompt(options: GeneratePromptOptions): string;
export function generatePrompt(
  a: string | GeneratePromptOptions,
  b?: string,
  c?: string
): string {
  const options: GeneratePromptOptions =
    typeof a === 'string'
      ? {
          projectName: a,
          srsStandard: b || 'ISO/IEC/IEEE 29148:2018',
          projectVision: c || '',
          promptSet: 'default'
        }
      : a;

  const {
    projectName,
    srsStandard,
    projectVision,
    promptSet = 'default',
    authorName = 'AI Generator',
    uploadedFiles = []
  } = options;

  if (srsStandard === 'ISO/IEC/IEEE 29148:2018') {
    if (promptSet === 'iso-strict') {
      return buildIso29148StrictPrompt({
        projectName,
        authorName,
        projectVision,
        srsStandard,
        uploadedFiles
      });
    }

    return buildIso29148Prompt(projectName, projectVision);
  }

  return buildIeee830Prompt(projectName, projectVision);
}

